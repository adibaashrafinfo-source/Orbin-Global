    public function test_long_invoices_paginate_with_a_repeating_header_and_keep_totals_together(): void
    {
        $ids = $this->stocked(60, '5');
        $sale = $this->checkout($this->payload(array_fill_keys($ids, '1')));
        $start = microtime(true);
        $memBefore = memory_get_peak_usage(true);
        $pdf = app(InvoicePdfService::class)->a4($sale->refresh());
        $seconds = microtime(true) - $start;
        $pages = $this->info($pdf)['pages'];
        $this->assertGreaterThan(1, $pages);
        $t = $this->text($pdf);
        $this->assertSame($pages, substr_count($t, 'Unit price'), 'the table header repeats on every page');
        $this->assertSame(1, substr_count($t, 'GRAND TOTAL'));
        $last = explode("\f", rtrim($t, "\f"));
        $this->assertStringContainsString('GRAND TOTAL', end($last), 'the totals sit on the last page');
        $this->assertStringContainsString("Customer's signature", end($last));
        $this->assertLessThan(15.0, $seconds, 'a 60-line invoice should render in a few seconds even on slow hosting');
        fwrite(STDERR, sprintf("\n[pdf-budget] 60 lines: %.2fs, %d pages, peak memory +%.1f MB, %.0f KB\n", $seconds, $pages, (memory_get_peak_usage(true) - $memBefore) / 1048576, strlen($pdf) / 1024));
    }

