    private function text(string $pdf): string
    {
        $tmp = tempnam(sys_get_temp_dir(), 'pdf');
        file_put_contents($tmp, $pdf);
        $out = shell_exec('pdftotext -layout '.escapeshellarg($tmp).' - 2>&1');
        @unlink($tmp);
        $this->assertIsString($out);

        return (string) $out;
    }

    /** @return array{pages: int, width: float} */
    private function info(string $pdf): array
    {
        $tmp = tempnam(sys_get_temp_dir(), 'pdf');
        file_put_contents($tmp, $pdf);
        $out = (string) shell_exec('pdfinfo '.escapeshellarg($tmp).' 2>&1');
        @unlink($tmp);
        preg_match('/Pages:\s+(\d+)/', $out, $p);
        preg_match('/Page size:\s+([\d.]+) x/', $out, $w);

        return ['pages' => (int) $p[1], 'width' => (float) $w[1]];
    }

