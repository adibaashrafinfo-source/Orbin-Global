    /** NFR-020: conjuncts, ra-phola and the taka sign must be shaped, not spelled out letter by letter. */
    public function test_bangla_conjuncts_are_shaped_and_match_the_reference_rendering(): void
    {
        $mpdf = PdfFactory::make('Bangla check', ['margin' => [10, 10, 10, 10]]);
        $mpdf->WriteHTML('<div style="font-size:30pt"><span style="font-family:bangla">স্ক্রিন &nbsp; ক্ষ &nbsp; র‍্যাম্প &nbsp; ৳ ১২,৫০০</span></div>');
        $pdf = $mpdf->Output('', 'S');
        $this->assertSame(1, $this->info($pdf)['pages']);
        $png = sys_get_temp_dir().'/bangla-render';
        file_put_contents($png.'.pdf', $pdf);
        shell_exec('pdftoppm -r 100 -png -singlefile -x 0 -y 0 -W 800 -H 120 '.escapeshellarg($png.'.pdf').' '.escapeshellarg($png));
        $this->assertFileExists($png.'.png');
        $reference = base_path('tests/fixtures/bangla-reference.png');
        if (! is_file($reference)) {
            File::copy($png.'.png', $reference);
            $this->fail('The reference image did not exist and was just created; check it by eye and commit it.');
        }
        $this->assertLessThan(0.01, $this->difference($png.'.png', $reference), 'the Bangla rendering moved away from the approved reference image');
    }

    /** Share of pixels that differ noticeably between two PNGs of the same size. */
    private function difference(string $a, string $b): float
    {
        $ia = imagecreatefrompng($a);
        $ib = imagecreatefrompng($b);
        $this->assertSame([imagesx($ib), imagesy($ib)], [imagesx($ia), imagesy($ia)]);
        $diff = 0;
        $total = imagesx($ia) * imagesy($ia);
        for ($x = 0; $x < imagesx($ia); $x++) {
            for ($y = 0; $y < imagesy($ia); $y++) {
                $pa = imagecolorat($ia, $x, $y);
                $pb = imagecolorat($ib, $x, $y);
                if (abs((($pa >> 16) & 255) - (($pb >> 16) & 255)) + abs((($pa >> 8) & 255) - (($pb >> 8) & 255)) + abs(($pa & 255) - ($pb & 255)) > 96) {
                    $diff++;
                }
            }
        }

        return $diff / $total;
    }

